interface LanguageContextType {
  currentLanguage: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  languageInfo: LanguageInfo;
  t: (key: string) => string;
  supportedLanguagesList: LanguageInfo[];
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguage] = useState<SupportedLanguage>(() => {
    const saved = localStorage.getItem('aurora_lang') as SupportedLanguage;
    if (saved && SUPPORTED_LANGUAGES[saved]) {
      return saved;
    }
    return 'te'; // Telugu default as requested for authentic Indic first experience
  });

  const setLanguage = (lang: SupportedLanguage) => {
    if (SUPPORTED_LANGUAGES[lang]) {
      setCurrentLanguage(lang);
      try {
        localStorage.setItem('aurora_lang', lang);
        if (typeof document !== 'undefined') {
          document.documentElement.lang = lang;
        }
        // Sync with user preferences if authenticated
        const token = localStorage.getItem('aurora_token');
        if (token) {
          fetch('/api/settings', {
            method: 'PUT',
            headers: {
              'Content-Type': 'application/json',
              Authorization: `Bearer ${token}`,
            },
            body: JSON.stringify({ defaultLanguage: lang }),
          }).catch(() => {});
        }
      } catch (err) {
        console.warn('Could not persist language preference:', err);
      }
    }
  };

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = currentLanguage;
    }
  }, [currentLanguage]);

  const languageInfo = SUPPORTED_LANGUAGES[currentLanguage] || SUPPORTED_LANGUAGES.en;

  // Pure in-memory translation helper function with robust fallbacks (zero runtime LLM calls)
  const t = (key: string): string => {
    if (!key) return '';
    // Normalise agent key aliases if needed
    let lookupKey = key;
    if (key === 'agent_learning_name') lookupKey = 'agent_language_learning_name';
    if (key === 'agent_learning_role') lookupKey = 'agent_language_learning_role';
    if (key === 'agent_learning_desc') lookupKey = 'agent_language_learning_desc';

    const currentDict = UI_TRANSLATIONS[currentLanguage];
    if (currentDict && currentDict[lookupKey]) {
      return currentDict[lookupKey];
    }
    const fallbackDict = UI_TRANSLATIONS.en;
    if (fallbackDict && fallbackDict[lookupKey]) {
      return fallbackDict[lookupKey];
    }
    // Strict safeguard: raw agent localization keys must never appear as visible text in the UI
    if (key.startsWith('agent_') && (key.endsWith('_name') || key.endsWith('_role') || key.endsWith('_desc'))) {
      return '';
    }
    return key;
  };

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage,
        setLanguage,
        languageInfo,
        t,
        supportedLanguagesList: Object.values(SUPPORTED_LANGUAGES),
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider');
  return context;
};
